import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";

const contractUrl = new URL("../src/patch-operations.json", import.meta.url);
const outputUrl = new URL("../../Flow/Coach/FlowPatchContract.generated.swift", import.meta.url);
const contract = JSON.parse(await readFile(contractUrl, "utf8"));

const integers = (values, label) => {
  assert.ok(values.length > 0, `${label} must not be empty`);
  values.forEach((value) => assert.ok(Number.isInteger(value), `${label} must contain integers`));
  return values;
};
const identifier = (value) => {
  assert.match(value, /^[A-Za-z_][A-Za-z0-9_]*$/);
  return value;
};
const range = (value, label) => {
  assert.ok(Number.isInteger(value.minimum) && Number.isInteger(value.maximum), `${label} must be an integer range`);
  assert.ok(value.minimum <= value.maximum, `${label} range is inverted`);
  return `${value.minimum}...${value.maximum}`;
};

const versions = integers(contract.patchSchemaVersions, "patchSchemaVersions");
const operations = Object.entries(contract.operationKindMinimumSchema);
operations.forEach(([kind, version]) => {
  identifier(kind);
  assert.ok(Number.isInteger(version) && versions.includes(version), `${kind} has an unsupported minimum schema`);
});
const switchCases = operations.map(([kind, version]) =>
  `            case .${kind}: return ${version}`,
).join("\n");

const generated = `// Generated by bridge-worker/scripts/generate-swift-patch-contract.mjs.
// Source: bridge-worker/src/patch-operations.json. Do not edit by hand.

enum FlowPatchContract {
    static let currentSchemaVersion = ${Math.max(...versions)}
    static let supportedSchemaVersions: Set<Int> = [${versions.join(", ")}]

${Object.entries(contract.stringBoundsUtf16).map(([name, value]) => `    static let ${identifier(name)} = ${value}`).join("\n")}

${Object.entries(contract.numericBounds).map(([name, value]) => `    static let ${identifier(name)}Range = ${range(value, name)}`).join("\n")}

    static let maximumRoutines = ${contract.collectionLimits.routines}
    static let maximumSections = ${contract.collectionLimits.sectionsPerRoutine}
    static let maximumExercisesPerSection = ${contract.collectionLimits.exercisesPerSection}
}

extension FlowRoutinePatchOperation {
    enum Kind: String, Codable, Equatable, CaseIterable {
${operations.map(([kind]) => `        case ${kind}`).join("\n")}

        var minimumSchemaVersion: Int {
            switch self {
${switchCases}
            }
        }
    }
}
`;

if (process.argv.includes("--check")) {
  assert.equal(
    await readFile(outputUrl, "utf8"),
    generated,
    "FlowPatchContract.generated.swift is stale; run npm run generate:patch-contract",
  );
  console.log("Swift patch contract is current.");
} else {
  await writeFile(outputUrl, generated);
  console.log("Generated Flow/Coach/FlowPatchContract.generated.swift");
}
